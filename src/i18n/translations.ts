export const translations: Record<Locale, Dict> = { en, de };

function lookup(dict: Dict, path: string): string | undefined {
  let node: Dict | string | undefined = dict;
  for (const part of path.split(".")) {
    if (typeof node !== "object" || node === null) return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
}

export function translate(
  locale: Locale,
  path: string,
  vars?: Record<string, string | number>,
): string {
  const raw = lookup(translations[locale], path) ?? lookup(translations.en, path) ?? path;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (str, [key, value]) => str.split(`{${key}}`).join(String(value)),
    raw,
  );
}
